#!/usr/bin/env bash
# -------------------------------------------------------------------------------------
# Regenerates src/lib/database.types.ts from the migrations.
# Builds the throwaway test database first (scripts/db-test.sh), then asks the Supabase CLI
# for the TypeScript types of the public schema. Run after adding or changing a migration.
#   DB_ADMIN_URL=postgresql://postgres:postgres@localhost:5432/postgres npm run db:types
# -------------------------------------------------------------------------------------
set -euo pipefail
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
ADMIN_URL="${DB_ADMIN_URL:-postgresql://postgres:postgres@localhost:5432/postgres}"
TEST_URL="$(printf '%s' "$ADMIN_URL" | sed -E 's#/[^/?]*(\?.*)?$##')/gsquad_test"

"$repo_root/scripts/db-test.sh" > /dev/null

target="$repo_root/src/lib/database.types.ts"
{
  echo '// GENERATED by scripts/db-types.sh from supabase/migrations. Do not edit by hand.'
  # sslmode=disable: the CI Postgres has no TLS, and db-test.sh has already confirmed this is a
  # local throwaway server, so nothing leaves the machine.
  npx --no-install supabase gen types typescript --db-url "${TEST_URL}?sslmode=disable" --schema public
} > "$target.tmp"
mv "$target.tmp" "$target"
echo "Wrote $target"
