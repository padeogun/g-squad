// -------------------------------------------------------------------------------------
// Turns the TEC Design System tokens (src/design-system/tokens.json) into CSS custom
// properties (src/design-system/tokens.css), which bundle.css and the app read.
//
//   node scripts/build-tokens.mjs           writes tokens.css
//   node scripts/build-tokens.mjs --check   fails if tokens.css is out of date (used in CI)
//
// Light theme is the default. Dark applies when the device prefers dark, unless the page
// sets data-theme="light"; data-theme="dark" forces it.
// -------------------------------------------------------------------------------------
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'design-system');
const tokens = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));

// One "--name: value;" line per token, indented for readability.
const line = (name, value) => `  --${name}: ${value};`;

// Colour and shadow tokens carry a light and a dark value.
const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
const light = themed.map((t) => line(t.name, t.value.light));
const dark = themed.map((t) => line(t.name, t.value.dark));

// Single-value tokens: spacing, radius, sizes, font families.
const fixed = [
  ...tokens.spacing.tokens.map((t) => line(t.name, t.value)),
  ...tokens.radius.tokens.map((t) => line(t.name, t.value)),
  ...tokens.size.tokens.map((t) => line(t.name, t.value)),
  ...Object.entries(tokens.type.families).map(([k, v]) => line(`font-${k}`, v)),
];

// Type styles become utility classes, e.g. .type-display-xl.
const typeClasses = tokens.type.groups
  .flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })))
  .map(
    (s) =>
      `.type-${s.name} { font-family: var(--font-${s.family}); font-size: ${s.fontSize}; ` +
      `line-height: ${s.lineHeight}; font-weight: ${s.fontWeight};` +
      (s.letterSpacing ? ` letter-spacing: ${s.letterSpacing};` : '') +
      ' }',
  );

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */

:root {
${fixed.join('\n')}
${light.join('\n')}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.map((l) => '  ' + l).join('\n')}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${dark.join('\n')}
  color-scheme: dark;
}

${typeClasses.join('\n')}
`;

const target = join(dir, 'tokens.css');

if (process.argv.includes('--check')) {
  // CI: the committed file must match what the tokens produce.
  const current = readFileSync(target, 'utf8');
  if (current !== css) {
    console.error('tokens.css is out of date. Run: npm run tokens');
    process.exit(1);
  }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(target, css);
  console.log(`Wrote ${target}`);
}
